import { validateSafeUrl } from "./api-service.js";

export function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

/**
 * Extracts a safe 11-character YouTube video ID from common YouTube URL formats.
 */
export function extractYoutubeId(rawUrl) {
  const safe = validateSafeUrl(rawUrl);
  if (!safe) return null;
  try {
    const u = new URL(safe);
    const host = u.hostname.replace(/^www\./, "");
    if (host === "youtu.be") {
      const id = u.pathname.slice(1).split("/")[0];
      return /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
    }
    if (host === "youtube.com" || host === "m.youtube.com" || host === "youtube-nocookie.com") {
      if (u.pathname === "/watch") {
        const id = u.searchParams.get("v");
        return id && /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
      }
      const match = u.pathname.match(/^\/(embed|shorts|live)\/([a-zA-Z0-9_-]{11})/);
      return match ? match[2] : null;
    }
  } catch {
    return null;
  }
  return null;
}

/**
 * Sanitizes trusted administrator ad markup before mounting into the DOM.
 * Rejects inline scripts and inline event handlers; only renders when
 * enabled === true AND trustedApproved === true.
 */
export function renderAdSlot(slotEl, adConfig, adLabelText) {
  if (!slotEl) return;
  const isActive = Boolean(
    adConfig &&
    adConfig.enabled === true &&
    adConfig.trustedApproved === true &&
    typeof adConfig.html === "string" &&
    adConfig.html.trim().length > 0
  );

  if (!isActive) {
    slotEl.hidden = true;
    slotEl.innerHTML = "";
    return;
  }

  const parser = new DOMParser();
  const doc = parser.parseFromString(adConfig.html, "text/html");
  doc.querySelectorAll("script, object, embed, form").forEach((el) => el.remove());

  doc.body.querySelectorAll("*").forEach((node) => {
    for (const attr of Array.from(node.attributes)) {
      const name = attr.name.toLowerCase();
      if (name.startsWith("on")) {
        node.removeAttribute(attr.name);
      } else if ((name === "href" || name === "src") && !validateSafeUrl(attr.value)) {
        node.removeAttribute(attr.name);
      }
    }
  });

  const cleaned = doc.body.innerHTML.trim();
  if (!cleaned) {
    slotEl.hidden = true;
    slotEl.innerHTML = "";
    return;
  }

  slotEl.hidden = false;
  slotEl.innerHTML = `
    <div class="ad-label">${escapeHtml(adLabelText)}</div>
    <div class="ad-body">${cleaned}</div>
  `;
}

