/**
 * Attaches 3D perspective tilt on mouse/touch hover for `.tilt-card` elements.
 */
export function attachTiltEffects(root = document) {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  root.querySelectorAll(".tilt-card").forEach((card) => {
    if (card.dataset.tiltBound === "1") return;
    card.dataset.tiltBound = "1";

    const updateTilt = (clientX, clientY) => {
      const rect = card.getBoundingClientRect();
      if (!rect.width || !rect.height) return;
      const px = (clientX - rect.left) / rect.width;
      const py = (clientY - rect.top) / rect.height;
      const rotX = (0.5 - py) * 9;
      const rotY = (px - 0.5) * 11;
      card.style.transform = `perspective(900px) rotateX(${rotX.toFixed(2)}deg) rotateY(${rotY.toFixed(2)}deg) translateY(-4px)`;
    };

    const resetTilt = () => {
      card.style.transform = "";
    };

    card.addEventListener("pointermove", (e) => {
      if (e.pointerType === "mouse") updateTilt(e.clientX, e.clientY);
    });
    card.addEventListener("pointerleave", resetTilt);
    card.addEventListener("touchstart", (e) => {
      if (e.touches[0]) updateTilt(e.touches[0].clientX, e.touches[0].clientY);
    }, { passive: true });
    card.addEventListener("touchend", resetTilt, { passive: true });
  });
}

/**
 * Observes `.reveal-on-scroll` elements for smooth entrance transitions.
 */
let revealObserver = null;
export function observeReveals(root = document) {
  const els = root.querySelectorAll(".reveal-on-scroll");
  if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    els.forEach((el) => el.classList.add("is-visible"));
    return;
  }

  if (!revealObserver) {
    revealObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            revealObserver.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.1, rootMargin: "0px 0px -30px 0px" }
    );
  }

  els.forEach((el) => revealObserver.observe(el));
}

export function showToast(message, type = "info") {
  const container = document.getElementById("toast-container");
  if (!container) return;

  const toast = document.createElement("div");
  toast.className = `toast toast-${type}`;
  toast.setAttribute("role", "status");
  toast.textContent = message;
  container.appendChild(toast);

  requestAnimationFrame(() => toast.classList.add("show"));
  setTimeout(() => {
    toast.classList.remove("show");
    setTimeout(() => toast.remove(), 320);
  }, 3000);
}
